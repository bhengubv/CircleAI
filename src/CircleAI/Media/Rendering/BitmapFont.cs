// BitmapFont.cs
//
// (Rendering 1.0) A tiny, self-contained 5x7 bitmap headline font so text
// overlays genuinely rasterise offline with zero font dependency. Covers
// A-Z, 0-9, space and common punctuation; lowercase folds to uppercase;
// unknown glyphs render as blank. Rich/multilingual typography is delegated
// to the HTML/WebView seam. The glyph data is original hand-authored art
// (no third-party font reproduced).

using System.Collections.Generic;

namespace CircleAI.Media.Rendering;

/// <summary>A fixed-cell 5x7 bitmap font. Each glyph is 7 rows of 5 cells ('#' = on).</summary>
public sealed class BitmapFont
{
    /// <summary>Glyph cell width.</summary>
    public const int Cols = 5;
    /// <summary>Glyph cell height.</summary>
    public const int Rows = 7;

    /// <summary>The shared default headline font.</summary>
    public static readonly BitmapFont Default = new();

    private readonly Dictionary<char, string[]> _glyphs;

    private BitmapFont() => _glyphs = Build();

    /// <summary>True if the character has a distinct glyph (space excluded).</summary>
    public bool HasGlyph(char c) => _glyphs.ContainsKey(Fold(c));

    /// <summary>
    /// Test whether cell (col,row) of character <paramref name="c"/> is "on".
    /// Returns false for spaces, unknown glyphs, or out-of-range cells.
    /// </summary>
    public bool IsPixelOn(char c, int col, int row)
    {
        if (col < 0 || col >= Cols || row < 0 || row >= Rows) return false;
        if (!_glyphs.TryGetValue(Fold(c), out var g)) return false;
        if (row >= g.Length) return false;
        var line = g[row];
        return col < line.Length && line[col] == '#';
    }

    private static char Fold(char c)
    {
        if (c is >= 'a' and <= 'z') return (char)(c - 32);
        return c;
    }

