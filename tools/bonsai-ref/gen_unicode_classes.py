# gen_unicode_classes.py
#
# Writes src/CircleAI/Inference/Managed/Text/UnicodeClasses.g.cs from the pinned fork's
# src/unicode-data.cpp, so the C# tokenizer classes every code point exactly as the fork
# does (the fork carries its own snapshot of the Unicode Character Database; .NET carries
# another, and the two disagree on whatever Unicode added in between).
#
#   python -I tools/bonsai-ref/gen_unicode_classes.py <prism-llama>/src/unicode-data.cpp \
#       src/CircleAI/Inference/Managed/Text/UnicodeClasses.g.cs
#
# llama.cpp is MIT, as is this repository.

import re
import sys

FORK_TAG = "prism-b10743-adfffbe"


def block(source, name):
    start = source.index(name)
    open_brace = source.index("{", start)
    close = source.index("};", open_brace)
    return source[open_brace + 1:close]


def main(source_path, out_path):
    source = open(source_path, encoding="utf-8").read()

    ranges = [(int(a, 16), int(b, 16))
              for a, b in re.findall(r"\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\}", block(source, "unicode_ranges_flags"))]
    assert ranges[0][0] == 0, "the first range must start at 0"
    assert ranges[-1][0] == 0x110000, "the last entry must be the 0x110000 sentinel"
    for (a, _), (b, _) in zip(ranges, ranges[1:]):
        assert a < b, f"ranges out of order at {a:#x}"
    for start, flags in ranges:
        assert flags <= 0xFF, f"flags {flags:#x} at {start:#x} need more than the category byte"

    whitespace = sorted(int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", block(source, "unicode_set_whitespace")))

    packed = [start << 8 | flags for start, flags in ranges]
    lines = []
    for i in range(0, len(packed), 8):
        lines.append("        " + ", ".join(f"0x{v:08X}" for v in packed[i:i + 8]) + ",")
    ws = ", ".join(f"0x{v:04X}" for v in whitespace)

    out = f"""// <auto-generated/>
// UnicodeClasses.g.cs - written by tools/bonsai-ref/gen_unicode_classes.py from the pinned fork's
// src/unicode-data.cpp ({FORK_TAG}; llama.cpp, MIT; itself generated from the Unicode
// Character Database). Do not edit by hand: run the script again.

namespace CircleAI.Inference.Managed.Text;

internal static partial class UnicodeClasses
{{
    // {len(ranges) - 1} ranges and the 0x110000 sentinel: (first code point << 8) | the fork's
    // category flags. A range ends where the next one starts.
    private static ReadOnlySpan<uint> Ranges =>
    [
{chr(10).join(lines)}
    ];

    // The fork's unicode_set_whitespace: the code points its \\s matches.
    private static ReadOnlySpan<int> WhitespaceSet => [{ws}];
}}
"""
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print(f"{len(ranges) - 1} ranges, {len(whitespace)} whitespace code points -> {out_path}")


main(sys.argv[1], sys.argv[2])
